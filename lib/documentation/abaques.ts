export const ABAQUE_KEYS = Object.keys(ABAQUES) as AbaqueType[];

/** Couleur associée à une puissance (dégradé vert → rouge). */
export function nmColor(nm: number): string {
  if (nm <= 6) return '#16a34a';
  if (nm <= 10) return '#65a30d';
  if (nm <= 15) return '#ca8a04';
  if (nm <= 20) return '#ea580c';
  if (nm <= 35) return '#dc2626';
  if (nm <= 60) return '#b91c1c';
  return '#7f1d1d';
}

export interface AbaqueResult { nm: number; hUsed: number; lUsed: number; hi: number; li: number; }

/** Puissance recommandée pour une dimension (snap au pas supérieur de l'abaque).
 *  `null` = dimensions hors abaque. */
export function requiredNm(type: AbaqueType, h: number, l: number): AbaqueResult | null {
  if (isNaN(h) || isNaN(l) || h <= 0 || l <= 0) return null;
  const ab = ABAQUES[type];
  const hi = ab.heights.findIndex((v) => v >= h);
  const li = ab.widths.findIndex((v) => v >= l);
  if (hi === -1 || li === -1) return null;
  return { nm: ab.data[hi][li], hUsed: ab.heights[hi], lUsed: ab.widths[li], hi, li };
}
